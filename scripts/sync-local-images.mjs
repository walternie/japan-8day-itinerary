import { copyFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { days } from "../data/itinerary.js";
import { imageCredits } from "../data/image-credits.js";
import { getStepImageBasename } from "../lib/site.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const imageDirectory = resolve(root, "assets", "images");
const extensionsPath = resolve(root, "data", "local-image-extensions.js");
const creditsPath = resolve(root, "data", "image-credits.js");

const EXT_PRIORITY = ["png", "jpeg", "jpg", "webp", "gif"];

function stemOf(filename) {
  return filename.replace(/\.(png|jpe?g|webp|gif)$/iu, "");
}

function extensionOf(filename) {
  const match = filename.match(/\.(png|jpe?g|webp|gif)$/iu);
  return match ? match[1].toLowerCase() : null;
}

const files = await readdir(imageDirectory);
const byStem = new Map();

for (const filename of files) {
  const stem = stemOf(filename);
  const ext = extensionOf(filename);
  if (!ext) continue;
  const current = byStem.get(stem) ?? [];
  current.push({ filename, ext });
  byStem.set(stem, current);
}

const steps = days.flatMap((day) => day.steps);
const preferredStems = new Set(steps.map((step) => getStepImageBasename(step)));
const extensions = {};

for (const step of steps) {
  const stem = getStepImageBasename(step);
  const candidates = [...(byStem.get(stem) ?? [])].sort(
    (a, b) => EXT_PRIORITY.indexOf(a.ext) - EXT_PRIORITY.indexOf(b.ext),
  );

  if (candidates.length === 0) {
    const dayPrefix = stem.slice(0, 2);
    const donor = files.find(
      (filename) =>
        filename.startsWith(`${dayPrefix}-`) &&
        /\.(png|jpe?g)$/iu.test(filename),
    );
    if (!donor) {
      throw new Error(`Missing image for ${stem}`);
    }
    const ext = extensionOf(donor);
    const target = `${stem}.${ext}`;
    await copyFile(resolve(imageDirectory, donor), resolve(imageDirectory, target));
    extensions[stem] = ext;
    console.log(`filled missing ${target} from ${donor}`);
    continue;
  }

  extensions[stem] = candidates[0].ext;
  for (const duplicate of candidates.slice(1)) {
    await unlink(resolve(imageDirectory, duplicate.filename));
    console.log(`removed duplicate ${duplicate.filename}`);
  }
}

for (const [stem, candidates] of byStem) {
  if (preferredStems.has(stem)) continue;
  for (const orphan of candidates) {
    await unlink(resolve(imageDirectory, orphan.filename));
    console.log(`removed orphan ${orphan.filename}`);
  }
}

await writeFile(
  extensionsPath,
  "// Auto-generated by scripts/sync-local-images.mjs — preferred extension per step image basename.\n" +
    `export const localImageExtensions = ${JSON.stringify(extensions, null, 2)};\n`,
  "utf8",
);

const stepById = new Map(steps.map((step) => [step.id, step]));
const updatedCredits = steps.map((step) => {
  const existing = imageCredits.find((credit) => credit.stepId === step.id);
  const stem = getStepImageBasename(step);
  const ext = extensions[stem] ?? "jpg";
  const localFile = `assets/images/${stem}.${ext}`;
  if (existing) {
    return { ...existing, localFile };
  }
  return {
    stepId: step.id,
    localFile,
    title: `Pending visual match — ${step.title}`,
    creator: "pending",
    license: "pending",
    licenseUrl: "https://loremflickr.com/",
    sourceUrl: "https://loremflickr.com/",
    retrievedAt: new Date().toISOString().slice(0, 10),
  };
});

await writeFile(
  creditsPath,
  "// Generated image credit metadata; localFile tracks the preferred on-disk extension.\n" +
    `export const imageCredits = ${JSON.stringify(updatedCredits, null, 2)};\n`,
  "utf8",
);

console.log(`Synced ${Object.keys(extensions).length} local image extensions.`);
